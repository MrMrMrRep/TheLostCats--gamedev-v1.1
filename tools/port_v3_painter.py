# Makes scripts/world/v3/v3_base.gd and v3_zones.gd (the game's v3 painter) from the
# style mocks tools/style_mock_v3.gd and tools/style_mock_v3_zones.gd: same drawing
# code, but on a canvas that can sit anywhere along the map (OX, W, H) instead
# of the fixed 1400x720 frame. Run after changing the mocks:  python3 tools/port_v3_painter.py
import re, sys
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..") + "/"

def drop_funcs(src, names):
    lines = src.split("\n")
    out, skip = [], False
    for ln in lines:
        m = re.match(r"func (\w+)\(", ln)
        if m:
            skip = m.group(1) in names
        elif skip and ln and not ln.startswith("\t") and not ln.startswith("#"):
            skip = False
        if not skip:
            out.append(ln)
    return "\n".join(out)

def common(s):
    s = s.replace("img.set_pixel(", "_put_px(").replace("img.get_pixel(", "_get_px(")
    s = re.sub(r"for (\w+) in W:", r"for \1 in range(OX, OX + W):", s)
    s = s.replace("range(maxi(x, 0), mini(x + w, W))", "range(maxi(x, OX), mini(x + w, OX + W))")
    s = re.sub(r"_rect\(0, ([^,]+), W, ", r"_rect(OX, \1, W, ", s)
    s = re.sub(r"range\(0, W, (\d+)\)", r"range(OX - posmod(OX, \1), OX + W, \1)", s)
    s = re.sub(r"range\((\d+), W, (\d+)\)", r"range(OX - posmod(OX, \2) + \1, OX + W, \2)", s)
    s = re.sub(r"range\(x0, W, (\d+)\)", r"range(x0, OX + W, \1)", s)
    s = s.replace("W - x0", "OX + W - x0")
    s = s.replace("while x < W:", "while x < OX + W:")
    s = s.replace("\tif x < 0 or y < 0 or x >= W or y >= H:\n\t\treturn false", "\tif not _inside(x, y):\n\t\treturn false")
    return s

b = open(root + "tools/style_mock_v3.gd").read()
b = b.replace("extends SceneTree", "extends RefCounted\n## GENERATED by tools/port_v3_painter.py from tools/style_mock_v3.gd: edit the mock, then rerun it.", 1)
b = b.replace("const W := 1400", "var W := 1400                               # canvas width (art px)\nvar OX := 0                                 # art x of the canvas's first column", 1)
b = b.replace("const H := 720", "var H := 720                                # canvas height (art px), y 0 = top of the mock frame", 1)
b = drop_funcs(b, {"_initialize", "_frame", "_band", "_render"})
b = common(b)
b = b.replace('''func _px(x: int, y: int, c: Color) -> void:
	if x < plot_l or x >= plot_r:
		return
	if x >= 0 and y >= 0 and x < W and y < H:
		_put_px(x, y, c)''', '''func _inside(x: int, y: int) -> bool:
	return x >= OX and y >= 0 and x < OX + W and y < H


func _put_px(x: int, y: int, c: Color) -> void:
	if x < plot_l or x >= plot_r:
		return
	if x >= OX and y >= 0 and x < OX + W and y < H:
		img.set_pixel(x - OX, y, c)


func _get_px(x: int, y: int) -> Color:
	if x >= OX and y >= 0 and x < OX + W and y < H:
		return img.get_pixel(x - OX, y)
	return Color(0, 0, 0, 0)


func _px(x: int, y: int, c: Color) -> void:
	if x < plot_l or x >= plot_r:
		return
	if x >= OX and y >= 0 and x < OX + W and y < H:
		img.set_pixel(x - OX, y, c)''')
b = b.replace('''	var r := Rect2i(x, y, w, h).intersection(Rect2i(0, 0, W, H))
	if r.size.x > 0 and r.size.y > 0:
		img.fill_rect(r, c)''', '''	var r := Rect2i(x, y, w, h).intersection(Rect2i(OX, 0, W, H))
	if r.size.x > 0 and r.size.y > 0:
		r.position.x -= OX
		img.fill_rect(r, c)''')
b = b.replace("const FONT5 := {", 'const FONT5 := {\n\t"J": "00111000100001000010000101001001100", "X": "10001100010101000100010101000110001",\n\t"Y": "10001100010101000100001000010000100", "Q": "01110100011000110001101011001001101",\n\t"\'": "00100001000100000000000000000000000", "-": "00000000000000001110000000000000000",', 1)
b = b.replace("var img: Image", """var img: Image
var windows: Array = []                     # [Rect2i (art px, mock coords), lit by day] per window drawn
var sign_override := ""                     # replaces a landmark's built-in name when set""", 1)
b = b.replace("""func _window(x: int, y: int, w: int, h: int, lace: bool, arched: bool) -> void:
""", """func _window(x: int, y: int, w: int, h: int, lace: bool, arched: bool) -> void:
	_note_window(x, y, w, h, int(_hash(x, y) * 10.0) in [3, 5] and not lace)
""", 1)
b += """

func _note_window(x: int, y: int, w: int, h: int, lit: bool) -> void:
	windows.append([Rect2i(x, y, w, h), lit])


func _sign(fallback: String) -> String:
	return sign_override if sign_override != "" else fallback
"""
open(root + "scripts/world/v3/v3_base.gd", "w").write(b)

z = open(root + "tools/style_mock_v3_zones.gd").read()
